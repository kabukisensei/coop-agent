#!/usr/bin/env python3
"""
coop init wizard — guided creation of .coop/project.yml.
Discovers what it can, asks only relevant integration questions, and emits a
minimal YAML contract without unused TODO sections.

Usage:
  lib/init_wizard.py <target-dir> [--template]

Without --template: run the guided wizard.
With --template: print the full documented example to stdout (legacy raw copy).
"""
import argparse
