def run_wizard(target_dir: Path) -> dict:
    sys.stderr.write("Let's set up your Cooptimize project contract.\n\n")
    cwd = target_dir.resolve()
    git = discover_git(cwd)

    repo_root = git.get("root") or str(cwd)
    repo_name = Path(repo_root).name or "repo"
    default_branch = git.get("branch") or "main"
    origin = git.get("origin") or ""
    user = git.get("user_name") or ""

    organization = ask_prefilled("Organization", "Cooptimize")
    client = ask_prefilled("Client / engagement", "")
    timezone = ask_prefilled("Timezone", discover_timezone())

    repo_name = ask_prefilled("Repository short name", repo_name)
    repo_description = ask_prefilled("Repository description", "Project source and docs")
    repo_local_path = ask_prefilled("Repository local path", repo_root)
    default_branch = ask_prefilled("Default branch", default_branch)

    use_fabric = read_confirm("Is this a Microsoft Fabric / Power BI engagement?", default=False)
    tenant_id = ""
    if use_fabric:
        tenant_id = ask_prefilled("Azure tenant ID (optional)", discover_tenant())

    use_tabular_editor = False
    te_path = ""
    if sys.platform == "win32":
        use_tabular_editor = read_confirm("Use Tabular Editor 3 for BPA rules?", default=False)
        if use_tabular_editor:
            te_path = ask_prefilled("Tabular Editor 3 executable path", discover_te_path())

    setup_lineage = read_confirm("Configure SQL + Power BI lineage docs now? (runs `coop-data-doc setup`)", default=False)

    return {
        "organization": organization,
        "client": client,
        "timezone": timezone,
        "default_branch": default_branch,
        "repo_name": repo_name,
        "repo_description": repo_description,
        "repo_local_path": repo_local_path,
        "repo_remote_name": "origin",
        "use_fabric": use_fabric,
        "tenant_id": tenant_id,
        "use_tabular_editor": use_tabular_editor,
        "te_path": te_path,
        "setup_lineage": setup_lineage,
    }


def run_lineage_setup(target: Path) -> None:
    """The user accepted the lineage-docs offer: run the coop-data-doc wizard.

    Inherits the terminal (no capture) so coop-data-doc's questionary prompts
    render; a missing binary or non-TTY run degrades to a friendly hint.
    """
    sys.stderr.write("\nLaunching coop-data-doc setup (Ctrl-C to skip)…\n")
    try:
        cmd = os.environ.get("COOP_DATA_DOC_BIN", "coop-data-doc")
        # On Windows, .bat/.cmd files can't be executed via CreateProcess directly;
        # route them through cmd.exe so PATH/PATHEXT resolution isn't needed.
        if sys.platform == "win32" and cmd.lower().endswith((".bat", ".cmd")):
            subprocess.run(["cmd.exe", "/c", cmd, "setup"], cwd=target)
        else:
            subprocess.run([cmd, "setup"], cwd=target)
    except FileNotFoundError:
        sys.stderr.write("coop-data-doc isn't installed — run `coop install`, then `coop data-doc setup`.\n")
    except Exception as exc:
        sys.stderr.write(f"coop-data-doc setup failed ({exc}). Run `coop data-doc setup` anytime.\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Cooptimize project init wizard.")
    parser.add_argument("target_dir", help="Directory to create .coop/project.yml in.")
    parser.add_argument("--template", action="store_true", help="Print the full legacy template instead of running the wizard.")
    args = parser.parse_args(argv)

    script_dir = Path(__file__).resolve().parent
    example = script_dir.parent / ".coop" / "project.example.yml"

    if args.template:
        if example.exists():
            print(example.read_text(encoding="utf-8"), end="")
        else:
            sys.stderr.write("Template not found.\n")
            return 1
        return 0

    target = Path(args.target_dir).resolve()
    target.mkdir(parents=True, exist_ok=True)
    coop_dir = target / ".coop"
    coop_dir.mkdir(exist_ok=True)
    dst = coop_dir / "project.yml"

    if dst.exists():
        sys.stderr.write(f"{dst} already exists — not overwriting.\n")
        return 1

    answers = run_wizard(target)
    yml = build_project_yml(answers)
    dst.write_text(yml, encoding="utf-8")
    sys.stderr.write(f"\nWrote {dst}\n")
    sys.stderr.write("Review it, then run: coop doctor\n")
    if answers.get("setup_lineage"):
        run_lineage_setup(target)
    return 0


if __name__ == "__main__":
    sys.exit(main())
